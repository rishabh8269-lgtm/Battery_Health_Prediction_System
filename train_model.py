from pathlib import Path
import json
import joblib
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

ROOT = Path(__file__).resolve().parent
DATA_PATH = ROOT / "data" / "battery_dataset.csv"
MODEL_DIR = ROOT / "models"
REPORT_DIR = ROOT / "reports"
MODEL_DIR.mkdir(exist_ok=True)
REPORT_DIR.mkdir(exist_ok=True)

FEATURES = [
    "Cycle_Count",
    "Avg_Temperature_C",
    "Avg_Cell_Voltage_V",
    "Avg_Current_A",
    "Depth_of_Discharge_Percent",
    "Charge_Rate_C",
]
TARGET = "SOH_Percent"

data = pd.read_csv(DATA_PATH)
X = data[FEATURES]
y = data[TARGET]
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42
)

model = RandomForestRegressor(
    n_estimators=180,
    max_depth=18,
    min_samples_leaf=2,
    random_state=42,
    n_jobs=-1
)
model.fit(X_train, y_train)
predictions = model.predict(X_test)

metrics = {
    "dataset_type": "synthetic_simulated",
    "rows": int(len(data)),
    "features": FEATURES,
    "target": TARGET,
    "test_size": 0.20,
    "mae_percentage_points": round(float(mean_absolute_error(y_test, predictions)), 3),
    "rmse_percentage_points": round(float(mean_squared_error(y_test, predictions) ** 0.5), 3),
    "r2": round(float(r2_score(y_test, predictions)), 4),
    "warning": "Metrics are measured on synthetic data generated by assumptions in this project. They do not establish accuracy on real batteries."
}
joblib.dump({"model": model, "features": FEATURES, "target": TARGET}, MODEL_DIR / "battery_soh_model.joblib")
(REPORT_DIR / "model_evaluation.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
print("Model trained and saved.")
print(json.dumps(metrics, indent=2))
